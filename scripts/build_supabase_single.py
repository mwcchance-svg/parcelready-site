#!/usr/bin/env python3
"""Build the paste-ready single-file Edge Function for the dashboard route.

Inlines worker/store-registry.json into supabase/src/index.ts in place of
its import, writing supabase/dist/parcelready-store.single.ts. Rerun
after any registry or code change.
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "supabase", "src", "index.ts")).read()
registry = json.load(open(os.path.join(ROOT, "worker", "store-registry.json")))
old = 'import registry from "../store-registry.json" with { type: "json" };'
assert old in src
single = src.replace(old, "const registry = " + json.dumps(registry) + ";")
single = ("// ParcelReady store function, single-file dashboard build.\n"
          "// Generated by scripts/build_supabase_single.py from supabase/src/index.ts\n"
          "// and the pack registry. Do not edit by hand.\n\n" + single)
out = os.path.join(ROOT, "supabase", "dist", "parcelready-store.single.ts")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w").write(single)
print("wrote", out, len(single), "bytes")
