#!/usr/bin/env python3
"""Build the paste-ready single-file Worker for the dashboard route.

Inlines worker/store-registry.json into worker/src/index.js in place of
its import, writing worker/dist/parcelready-store.single.js. Rerun after
any registry or code change; the dashboard paste always uses this file.
"""
import json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = open(os.path.join(ROOT, "worker", "src", "index.js")).read()
registry = json.load(open(os.path.join(ROOT, "worker", "store-registry.json")))
old = 'import registry from "../store-registry.json";'
assert old in src
single = src.replace(old, "const registry = " + json.dumps(registry) + ";")
single = ("// ParcelReady store worker, single-file dashboard build.\n"
          "// Generated by scripts/build_single_file.py from worker/src/index.js\n"
          "// and worker/store-registry.json. Do not edit by hand.\n\n" + single)
out = os.path.join(ROOT, "worker", "dist", "parcelready-store.single.js")
open(out, "w").write(single)
print("wrote", out, len(single), "bytes")
